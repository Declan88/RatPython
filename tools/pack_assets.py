"""
Packs the game's Assets folder into encrypted, one-file-per-asset form (see
Modules/Assets/pack_format.py for the format and why).

    python tools/pack_assets.py                       -> build_nuitka/packed/Assets/
    python tools/pack_assets.py --out some/folder     -> some/folder/Assets/
    python tools/pack_assets.py --verify              -> also decrypt everything back and compare

The secret key lives in asset_key.bin at the project root (made on first run; git-ignored - BACK IT UP:
a new key re-encrypts every file, so every player would re-download the whole game on the next update,
and builds made with different keys can't read each other's packs). This tool also writes the key into
Modules/Assets/_asset_key.py (also git-ignored), which the game imports so the compiled program can
decrypt. Build order: run this first, then compile.

Only the output folder is touched, never Assets itself. Unchanged blobs aren't rewritten, and blobs of
deleted assets are removed.
"""

import argparse
import hashlib
import os
import secrets
import sys
import time
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from Modules.Assets import pack_format as fmt        # noqa: E402

KEY_FILE = ROOT / "asset_key.bin"
KEY_MODULE = ROOT / "Modules" / "Assets" / "_asset_key.py"

# Never shipped (same exclusions the Nuitka scripts use): scene-authoring leftovers and source files.
EXCLUDE_DIRS = ("lightmaps/torusscene",)
EXCLUDE_SUFFIXES = (".blend", ".blend1")


def load_or_create_key():
    if KEY_FILE.exists():
        key = KEY_FILE.read_bytes()
        if len(key) != 32:
            sys.exit(f"{KEY_FILE} is not a 32-byte key - refusing to continue")
    else:
        key = secrets.token_bytes(32)
        KEY_FILE.write_bytes(key)
        print(f"Created a new key: {KEY_FILE}  (back this file up)")
    # The key is stored as two int tuples that only combine into it when the module runs, never as a literal:
    # a literal (b"...", or a hex string) sits in plain sight in the compiled exe, where `strings` finds it.
    # Still obfuscation - the program has to rebuild the key to decrypt - just not trivially greppable.
    mask = hashlib.sha256(b"asset-key-mask|" + key).digest()
    part_a = tuple(mask)
    part_b = tuple(k ^ m for k, m in zip(key, mask))
    source = (
        '"""GENERATED by tools/pack_assets.py - the asset decryption key. Git-ignored; do not edit."""\n'
        f"_A = {part_a!r}\n"
        f"_B = {part_b!r}\n"
        "KEY = bytes(a ^ b for a, b in zip(_A, _B))\n"
    )
    if not KEY_MODULE.exists() or KEY_MODULE.read_text() != source:
        KEY_MODULE.write_text(source)
    return key


def collect(assets):
    files = []
    for path in sorted(assets.rglob("*")):
        if not path.is_file():
            continue
        rel = path.relative_to(assets).as_posix()
        low = rel.lower()
        if any(low == d or low.startswith(d + "/") for d in EXCLUDE_DIRS) or low.endswith(EXCLUDE_SUFFIXES):
            continue
        if low in (fmt.INDEX_NAME,) or low.startswith(fmt.BLOB_DIR + "/"):
            continue                 # never pack a previous pack
        files.append((rel, path))
    return files


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--assets", default=str(ROOT / "Assets"), help="the plain Assets folder")
    parser.add_argument("--out", default=str(ROOT / "build_nuitka" / "packed"),
                        help="output folder; the pack goes in <out>/Assets")
    parser.add_argument("--verify", action="store_true", help="decrypt every blob again and compare with the source")
    args = parser.parse_args()

    assets = Path(args.assets)
    out = Path(args.out) / "Assets"
    blob_dir = out / fmt.BLOB_DIR
    blob_dir.mkdir(parents=True, exist_ok=True)
    key = load_or_create_key()

    started = time.perf_counter()
    index, wanted = {}, set()
    written = kept = 0
    plain_bytes = packed_bytes = 0
    files = collect(assets)
    for n, (rel, path) in enumerate(files, 1):
        data = path.read_bytes()
        norm = fmt.normalize(rel)
        name = fmt.blob_name(key, norm)
        blob = fmt.encrypt(data, key, norm.encode("utf-8"))
        target = blob_dir / name
        if target.exists() and target.stat().st_size == len(blob) and target.read_bytes() == blob:
            kept += 1
        else:
            target.write_bytes(blob)
            written += 1
        wanted.add(name)
        index[norm] = [rel, name, len(data), int(path.stat().st_mtime)]
        plain_bytes += len(data)
        packed_bytes += len(blob)
        if n % 500 == 0:
            print(f"  {n}/{len(files)} ...")

    removed = 0
    for old in blob_dir.iterdir():
        if old.name not in wanted:
            old.unlink()
            removed += 1
    (out / fmt.INDEX_NAME).write_bytes(fmt.encode_index(index, key))

    print(f"{len(files)} assets, {plain_bytes / 2**20:.1f} MB -> {packed_bytes / 2**20:.1f} MB packed "
          f"({written} blobs written, {kept} unchanged, {removed} stale removed) in "
          f"{time.perf_counter() - started:.1f}s -> {out}")

    if args.verify:
        loaded = fmt.decode_index((out / fmt.INDEX_NAME).read_bytes(), key)
        bad = 0
        for norm, (rel, name, size, _mtime) in loaded.items():
            data = fmt.decrypt((blob_dir / name).read_bytes(), key, norm.encode("utf-8"))
            if data != (assets / rel).read_bytes():
                bad += 1
                print("MISMATCH:", rel)
        print(f"verify: {len(loaded)} assets decrypted back, {bad} mismatches")
        sys.exit(1 if bad else 0)


if __name__ == "__main__":
    main()
