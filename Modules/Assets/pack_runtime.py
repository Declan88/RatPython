"""
Runtime side of the packed (encrypted) assets - see pack_format.py for the format and the reasoning.

install() makes a packed build behave exactly like one with plain asset files, without touching the ~50
places in the game that open assets by a path like "Assets/Models/foo.glb": it wraps the Python/library
functions that read files so that any path under the Assets folder that is in the pack index is served
from its decrypted blob. Everything else (saves, logs, anything outside Assets, a file that isn't in the
pack) goes to the real filesystem untouched, and writes always do.

Covered: open()/io.open, pathlib.Path (open/read_bytes/read_text/exists/is_file/is_dir/stat/iterdir),
os.path.exists/isfile/isdir/getmtime/getsize, pygame.image.load, pygame.font.Font, pygame.mixer.Sound,
and OpenEXR.File (which can only read a real path: the blob is decrypted to a private temp file that is
deleted again right away). PIL, numpy.load and the Panda3D collision-cache reader all read through open()
or Path.read_bytes(), so they work unchanged.

With no pack present (a normal `python app.py` run from the source tree) install() does nothing at all, so
development is unaffected.
"""

import atexit
import builtins
import io
import os
import pathlib
import shutil
import stat as stat_module
import tempfile
from collections import OrderedDict

from . import pack_format as fmt

try:
    from ._asset_key import KEY as _KEY       # generated by tools/pack_assets.py
except ImportError:
    _KEY = None

ASSETS_DIR = "Assets"
_CACHE_LIMIT = 192 * 1024 * 1024      # decrypted bytes kept in memory (audio plays the same file again and again)
_CACHE_ITEM_LIMIT = 8 * 1024 * 1024   # bigger files (models, lightmaps) are read once and not kept

_installed = False
_index = {}              # normalized path -> [real relative path, blob name, size, mtime]
_dirs = {}               # normalized directory -> {child name (real case): is_dir}
_root_abs = ""
_root_norm = ""
_cache = OrderedDict()
_cache_bytes = 0
_tmp_dir = None
_real = {}               # the original functions, captured before they are replaced


# ---------------------------------------------------------------------------- lookup


def _entry(path):
    """(normalized key, index entry) when `path` is a packed asset, else None. Cheap for the common
    case of a path that has nothing to do with Assets."""
    try:
        p = os.fspath(path)
    except TypeError:
        return None
    if not isinstance(p, str) or "ssets" not in p.lower():
        return None
    key = _relative_key(p)
    if key is None:
        return None
    entry = _index.get(key)
    return (key, entry) if entry is not None else None


def _relative_key(p):
    # Lower-cased explicitly, like the index keys (pack_format.normalize): os.path.normcase only lower-cases on
    # Windows, so on macOS/Linux every path with a capital letter used to miss the pack.
    full = os.path.abspath(p).replace("\\", "/").lower()
    if full == _root_norm:
        return ""
    if full.startswith(_root_norm + "/"):
        return full[len(_root_norm) + 1:]
    return None


def _dir_children(path):
    """{child name: is_dir} when `path` is a directory inside the pack, else None."""
    try:
        p = os.fspath(path)
    except TypeError:
        return None
    if not isinstance(p, str) or "ssets" not in p.lower():
        return None
    key = _relative_key(p)
    return _dirs.get(key) if key is not None else None


def _read(key, entry):
    """The decrypted bytes of a packed asset."""
    global _cache_bytes
    data = _cache.get(key)
    if data is not None:
        _cache.move_to_end(key)
        return data
    blob_path = os.path.join(ASSETS_DIR, fmt.BLOB_DIR, entry[1])
    with _real["open"](blob_path, "rb") as f:
        blob = f.read()
    data = fmt.decrypt(blob, _KEY, key.encode("utf-8"))
    if len(data) <= _CACHE_ITEM_LIMIT:
        _cache[key] = data
        _cache_bytes += len(data)
        while _cache_bytes > _CACHE_LIMIT and _cache:
            _, old = _cache.popitem(last=False)
            _cache_bytes -= len(old)
    return data


def read_asset(path):
    """The bytes of a packed asset, or None if `path` isn't in the pack."""
    hit = _entry(path)
    return None if hit is None else _read(*hit)


# ---------------------------------------------------------------------------- open() and pathlib


def _is_read_mode(mode):
    return not any(c in mode for c in "wax+")


def _open(file, mode="r", buffering=-1, encoding=None, errors=None, newline=None, closefd=True, opener=None):
    if isinstance(mode, str) and _is_read_mode(mode):
        hit = _entry(file)
        if hit is not None:
            data = _read(*hit)
            if "b" in mode:
                return io.BytesIO(data)
            return io.TextIOWrapper(io.BytesIO(data), encoding=encoding, errors=errors, newline=newline)
    return _real["open"](file, mode, buffering, encoding, errors, newline, closefd, opener)


def _path_open(self, mode="r", buffering=-1, encoding=None, errors=None, newline=None):
    if _is_read_mode(mode) and _entry(self) is not None:
        return _open(self, mode, buffering, encoding, errors, newline)
    return _real["path_open"](self, mode, buffering, encoding, errors, newline)


def _fake_stat(entry, directory=False):
    size, mtime = (0, 0) if directory else (entry[2], entry[3])
    mode = (stat_module.S_IFDIR | 0o555) if directory else (stat_module.S_IFREG | 0o444)
    return os.stat_result((mode, 0, 0, 1, 0, 0, size, mtime, mtime, mtime))


def _path_stat(self, *args, **kwargs):
    hit = _entry(self)
    if hit is not None:
        return _fake_stat(hit[1])
    if _dir_children(self) is not None:
        return _fake_stat(None, directory=True)
    return _real["path_stat"](self, *args, **kwargs)


def _path_exists(self, *args, **kwargs):
    if _entry(self) is not None or _dir_children(self) is not None:
        return True
    return _real["path_exists"](self, *args, **kwargs)


def _path_is_file(self, *args, **kwargs):
    if _entry(self) is not None:
        return True
    return _real["path_is_file"](self, *args, **kwargs)


def _path_is_dir(self, *args, **kwargs):
    if _dir_children(self) is not None:
        return True
    return _real["path_is_dir"](self, *args, **kwargs)


def _path_iterdir(self, *args, **kwargs):
    children = _dir_children(self)
    if children is None:
        yield from _real["path_iterdir"](self, *args, **kwargs)
        return
    seen = set()
    for name in sorted(children):
        seen.add(name.lower())
        yield self / name
    try:                                    # plus anything the game has written next to the pack since
        for extra in _real["path_iterdir"](self, *args, **kwargs):
            if extra.name.lower() not in seen:
                yield extra
    except OSError:
        pass


def _os_exists(path):
    return _entry(path) is not None or _dir_children(path) is not None or _real["exists"](path)


def _os_isfile(path):
    return _entry(path) is not None or _real["isfile"](path)


def _os_isdir(path):
    return _dir_children(path) is not None or _real["isdir"](path)


def _os_getmtime(path):
    hit = _entry(path)
    return float(hit[1][3]) if hit is not None else _real["getmtime"](path)


def _os_getsize(path):
    hit = _entry(path)
    return hit[1][2] if hit is not None else _real["getsize"](path)


# ---------------------------------------------------------------------------- pygame and OpenEXR


def _install_pygame():
    try:
        import pygame
    except ImportError:
        return
    real_load = pygame.image.load

    def load(file, namehint=""):
        hit = _entry(file) if isinstance(file, (str, os.PathLike)) else None
        if hit is None:
            return real_load(file, namehint) if namehint else real_load(file)
        return real_load(io.BytesIO(_read(*hit)), namehint or os.path.basename(hit[1][0]))

    pygame.image.load = load

    real_font = pygame.font.Font

    class Font(real_font):
        def __init__(self, file=None, size=20, *args, **kwargs):
            hit = _entry(file) if isinstance(file, (str, os.PathLike)) else None
            if hit is not None:
                file = io.BytesIO(_read(*hit))
            self._source = file            # pygame reads through this object for the font's whole life
            super().__init__(file, size, *args, **kwargs)

    pygame.font.Font = Font
    if hasattr(pygame.font, "FontType"):
        pygame.font.FontType = Font

    real_sound = pygame.mixer.Sound

    class Sound(real_sound):
        def __init__(self, file=None, buffer=None, array=None):
            if file is not None:
                hit = _entry(file) if isinstance(file, (str, os.PathLike)) else None
                if hit is not None:
                    file = io.BytesIO(_read(*hit))
                super().__init__(file=file)
            elif buffer is not None:
                super().__init__(buffer=buffer)
            else:
                super().__init__(array=array)

    pygame.mixer.Sound = Sound


def _private_tmp():
    global _tmp_dir
    if _tmp_dir is None:
        _tmp_dir = tempfile.mkdtemp(prefix="rk_")
        atexit.register(shutil.rmtree, _tmp_dir, True)
    return _tmp_dir


def _install_openexr():
    try:
        import OpenEXR
    except ImportError:
        return
    real_file = OpenEXR.File

    def File(*args, **kwargs):
        if len(args) == 1 and not kwargs and isinstance(args[0], (str, os.PathLike)):
            hit = _entry(args[0])
            if hit is not None:
                # OpenEXR can only read a real file: decrypt to a private temp file, read, delete at once.
                tmp = os.path.join(_private_tmp(), hit[0].replace("/", "_"))
                with _real["open"](tmp, "wb") as f:
                    f.write(_read(*hit))
                try:
                    return real_file(tmp)
                finally:
                    try:
                        os.remove(tmp)
                    except OSError:
                        pass                # still open on Windows: removed with the folder at exit
        return real_file(*args, **kwargs)

    OpenEXR.File = File


# ---------------------------------------------------------------------------- install


def install():
    """Activates the pack if there is one. Returns True when assets are now being served from it."""
    global _installed, _index, _dirs, _root_abs, _root_norm
    if _installed:
        return True
    index_path = os.path.join(ASSETS_DIR, fmt.INDEX_NAME)
    if _KEY is None or not os.path.isfile(index_path):
        return False
    with builtins.open(index_path, "rb") as f:
        raw = f.read()
    try:
        _index = fmt.decode_index(raw, _KEY)
    except Exception as e:
        print(f"[assets] pack found but not readable ({e}) - using plain files")
        return False
    _root_abs = os.path.abspath(ASSETS_DIR)
    _root_norm = _root_abs.replace("\\", "/").lower()

    _dirs = {"": {}}
    for norm, entry in _index.items():
        parts = entry[0].replace("\\", "/").split("/")
        low = norm.split("/")
        for depth in range(len(parts)):
            parent = "/".join(low[:depth])
            _dirs.setdefault(parent, {})
            _dirs[parent][parts[depth]] = depth < len(parts) - 1
            if depth < len(parts) - 1:
                _dirs.setdefault("/".join(low[:depth + 1]), {})

    Path = pathlib.Path
    _real.update(
        open=builtins.open, path_open=Path.open, path_stat=Path.stat, path_exists=Path.exists,
        path_is_file=Path.is_file, path_is_dir=Path.is_dir, path_iterdir=Path.iterdir,
        exists=os.path.exists, isfile=os.path.isfile, isdir=os.path.isdir,
        getmtime=os.path.getmtime, getsize=os.path.getsize,
    )
    builtins.open = _open
    io.open = _open
    Path.open = _path_open
    Path.stat = _path_stat
    Path.exists = _path_exists
    Path.is_file = _path_is_file
    Path.is_dir = _path_is_dir
    Path.iterdir = _path_iterdir
    os.path.exists = _os_exists
    os.path.isfile = _os_isfile
    os.path.isdir = _os_isdir
    os.path.getmtime = _os_getmtime
    os.path.getsize = _os_getsize
    _install_pygame()
    _install_openexr()
    _installed = True
    print(f"[assets] serving {len(_index)} packed assets from {ASSETS_DIR}/{fmt.BLOB_DIR}")
    return True
